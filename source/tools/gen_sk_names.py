"""(Fm1Studio) firmware/src/kawa_sk_names.h: the names Skiff's engine code (firmware/src/skiff/) defines that KAWA's own
code also uses, renamed SK_* inside the block of kawa_sk.c that builds Skiff's code (and undone after it).

    python3 tools/gen_sk_names.py        (again after a Skiff engine is added to skiff/)"""
import re
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "firmware" / "src"
GEN = SRC.parent / "gen"
IDENT = re.compile(r"\b[A-Za-z_]\w*\b")
# what a C file defines: functions, variables, enum values, macros, typedefs
DEFINES = [
    re.compile(r"^#\s*define\s+([A-Za-z_]\w*)", re.M),
    re.compile(r"^(?:static|const|typedef|struct|enum|void|unsigned|signed|u?int\w*|char)\b[^;{=(]*?\b([A-Za-z_]\w*)\s*(?:\(|\[|=)", re.M),
    re.compile(r"^}\s*([A-Za-z_]\w*)\s*;", re.M),
]


def strip_comments(text: str) -> str:
    return re.sub(r"//[^\n]*", " ", re.sub(r"/\*.*?\*/", " ", text, flags=re.S))


def enum_values(text: str) -> set[str]:
    names = set()
    for body in re.findall(r"enum\s*\w*\s*{(.*?)}", text, flags=re.S):
        for item in body.split(","):
            m = re.match(r"\s*([A-Za-z_]\w*)", item)
            if m:
                names.add(m.group(1))
    return names


def defined(text: str) -> set[str]:
    text = strip_comments(text)
    names = enum_values(text)
    for rx in DEFINES:
        names.update(rx.findall(text))
    return names


def main() -> None:
    skiff, skiff_macros = set(), set()
    for f in sorted((SRC / "skiff").iterdir()):
        if f.suffix in (".c", ".h"):
            text = f.read_text(encoding="utf-8", errors="replace")
            skiff |= defined(text)
            skiff_macros |= set(DEFINES[0].findall(strip_comments(text)))
    kawa, kawa_macros = set(), set()
    for f in list(SRC.glob("*.c")) + list(SRC.glob("*.h")) + list(GEN.glob("*.h")) + list((SRC.parent / "hal").glob("*.h")):
        if f.name in ("kawa_sk.c", "kawa_sk_names.h"):
            continue
        text = strip_comments(f.read_text(encoding="utf-8", errors="replace"))
        kawa |= set(IDENT.findall(text))
        kawa_macros |= set(DEFINES[0].findall(text))
    keep = {"NELEM", "FS", "CTL", "clamp", "blep", "pitch_inc", "preset_t", "SINE"}   # handled in kawa_sk.c itself
    common = sorted(n for n in skiff & kawa if n not in keep and not n.startswith("__"))
    # a macro on either side cannot be renamed: KAWA's is put aside while Skiff's code builds, and comes back after
    macros = [n for n in common if n in skiff_macros or n in kawa_macros]
    renamed = [n for n in common if n not in macros]
    lines = ["/* generated by tools/gen_sk_names.py: Skiff's names KAWA also has (kawa_sk.c) */",
             "#ifndef SK_UNDO_NAMES"]
    lines += [f"#define {n} SK_{n}" for n in renamed]
    lines += [f'#pragma push_macro("{n}")\n#undef {n}' for n in macros]
    lines += ["#else"] + [f"#undef {n}" for n in renamed]
    lines += [f'#undef {n}\n#pragma pop_macro("{n}")' for n in macros]
    lines += ["#endif", ""]
    (SRC / "kawa_sk_names.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(renamed)} renommés : {' '.join(renamed)}")
    print(f"{len(macros)} macros mises de côté : {' '.join(macros)}")


if __name__ == "__main__":
    main()
