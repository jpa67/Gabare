"""(Gabare) The FM-1's 128 original voices (M-VAVE firmware V15) -> firmware/gen/kawa_mvave.h.

  python3 tools/gen_mvave.py mvave-v15-voices.bin

The input is the 128 voices of app/fm_factory.inc in m-vave/fm1_open (Apache-2.0, by 珠海笙科智能科技有限公司 / M-VAVE),
with the flash compression taken off and nothing else changed: 128 packed DX7 voices (VMEM, 128 bytes each), slot 1
first, SHA-256 ecad0b86...ad25 (the file Fm1Studio carries, src/Fm1Studio.Core/Presets/mvave-v15-voices.bin). They stay
under the Apache-2.0 licence (source/LICENSES/Apache-2.0-mvave.txt); Gabare plays them after KAWA's FM sounds (kawa_edit.c).
"""
import hashlib
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "kawa_mvave.h"
SHA256 = "ecad0b8620f9d784d46c8da1e3c5de02c40214649ed8dec218026431046aad25"


def main() -> int:
    data = Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        sys.exit("not the 128 voices of fm1_open's app/fm_factory.inc (SHA-256 differs)")
    if len(data) != 128 * 128:
        sys.exit("128 voices of 128 bytes expected")
    lines = [
        "/* generated by tools/gen_mvave.py: the FM-1's 128 original voices (M-VAVE firmware V15), packed DX7 voices",
        " * (VMEM, 128 bytes), slot 1 first. From app/fm_factory.inc of https://github.com/m-vave/fm1_open, decompressed,",
        " * otherwise unchanged. Copyright 珠海笙科智能科技有限公司 (M-VAVE); Apache License 2.0, see source/LICENSES/Apache-2.0-mvave.txt. */",
        "#pragma once",
        "#include <stdint.h>",
        "#define MV_N 128u",
        "static const uint8_t MV_VOICE[MV_N][128] = {",
    ]
    for v in range(128):
        voice = data[v * 128:(v + 1) * 128]
        name = bytes(c if 0x20 <= c < 0x7F else 0x20 for c in voice[118:128]).decode().rstrip()
        lines.append(f"    {{{', '.join(str(b) for b in voice)}}},   /* {v + 1}: {name.replace('*/', '* /')} */")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT}: {len(data) // 128} voices")
    return 0


if __name__ == "__main__":
    sys.exit(main())
